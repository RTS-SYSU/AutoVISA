"""Typed statements shared by rule execution, the workspace and the evidence checker."""

from copy import deepcopy
from platform_core.evidence.terms import Rejected

from platform_core.analysis_ir.case11 import var, call, binary, quantify, proposition
from platform_core.analysis_ir.language import expression, SYMBOLS

#: Additional typed references resolve to the already mapped W01 mathematical definitions.
SIGNATURES = {**SYMBOLS,
    "ir_fig3_accepts":(["TaskSet"],"Prop","fig3_accepts"),
    "ir_initial":(["TaskSet","Task"],"Nat","initial"),
    "ir_workload":(["TaskSet","Task","Nat"],"Nat","workload"),
    "job_lookup":(["Arrivals","Nat"],"OptionJob","(fun a id => a id)"),
    "some_job":(["Job"],"OptionJob","(@Some Job)"),
    "job_task":(["Job"],"Nat","job_task"),
    "release":(["Job"],"Nat","job_release"),
    "demand":(["Job"],"Nat","job_demand"),
    "service":(["Schedule","Nat","Nat","Nat"],"Nat","service_from"),
    "interference":(["Schedule","Nat","Nat","Nat"],"Nat","interference_from"),
    "ready":(["Schedule","Nat","Job","Nat"],"Prop","ready"),
    "dispatches":(["Schedule","Nat","Nat"],"Prop","(fun s t id => s t = Some id)"),
}


def render(tree):
    """Render a typed proposition in the fixed model namespace.

    @param tree Analysis expression with explicit quantifiers and assumptions.
    @return Rocq proposition text accepted by the evidence module.
    @raise ValueError If the expression does not have proposition type.
    """
    # @var sort, text Inferred type and syntax generated by the shared finite IR language.
    sort, text = expression(tree,{},SIGNATURES)
    if sort != "Prop":
        raise ValueError("A derivation claim must have sort Prop")
    return text


def implies(premises, conclusion):
    """Bind a complete ordered list of jointly required premises.

    @param premises Statements that must all hold, in application order.
    @param conclusion Required conclusion in the same variable scope.
    @return Nested implication expression.
    """
    for premise in reversed(premises):
        conclusion = binary("implies",premise,conclusion)
    return conclusion


def witness(hp, p):
    """Express an accepting workload point within the own-task deadline.

    @param hp Higher-priority task prefix expression.
    @param p Own-task expression.
    @return Existential bound with both deadline and workload conditions.
    """
    # @var w Bound witness tick; both inequalities refer to this same value.
    w = var("w")
    return {"op":"exists","name":"w","sort":"Nat","body":binary("and",
        binary("le",w,call("deadline",p)),binary("le",call("ir_workload",hp,p,w),w))}


def task_witnesses(ts):
    """Require a feasible workload witness for every task in a priority-ordered set.

    @param ts Task-set expression.
    @return Universally quantified indexed task obligation.
    """
    # @var i, p Task index and its associated task record.
    i,p = var("i"),var("p")
    return quantify([["i","Nat"],["p","Task"]],implies(
        [binary("eq",call("lookup",ts,i),call("some_task",p))],witness(call("prefix",i,ts),p)))


def claims():
    """Build mathematically distinct forward facts and backward obligations.

    @return Stable keys mapped to explicit typed propositions.
    """
    # @var hp, p, t Arbitrary prefix, own task and starting iteration time.
    hp,p,t = map(var,("hp","p","t"))
    # @var ts, a, s Arbitrary task set, legal job population and schedule.
    ts,a,s = map(var,("ts","a","s"))
    # @var model Conditions shared by every method-level scheduling guarantee.
    model = [call("taskset_wf",ts),call("legal_arrivals",ts,a),
             call("bounded_demands",ts,a),call("valid_dm_schedule",a,s)]
    # @var i, jid, j Index, job identity and job record used by the direct backward route.
    i,jid,j = map(var,("i","jid","j"))
    # @var completion Service supplied before the absolute deadline equals actual demand.
    completion = binary("eq",call("service",s,jid,call("release",j),
                        binary("add",call("release",j),call("deadline",p))),call("demand",j))
    result = {
        "trace_witness":quantify([["hp","TaskSet"],["p","Task"],["t","Nat"]],
            implies([call("accepts_from",hp,p,t)],witness(hp,p))),
        "trace_guard":quantify([["hp","TaskSet"],["p","Task"],["t","Nat"]],
            implies([call("accepts_from",hp,p,t)],binary("le",t,call("deadline",p)))),
        "cost_lower_bound":quantify([["hp","TaskSet"],["p","Task"],["t","Nat"]],
            binary("le",call("cost",p),call("ir_workload",hp,p,t))),
        "task_witnesses":quantify([["ts","TaskSet"]],
            implies([call("ir_fig3_accepts",ts)],task_witnesses(ts))),
        "response_bridge":quantify([["ts","TaskSet"],["a","Arrivals"],["s","Schedule"]],
            implies([*model,task_witnesses(ts)],call("deadlines_met",ts,a,s))),
        "direct_jobs":quantify([["ts","TaskSet"],["a","Arrivals"],["s","Schedule"]],
            implies([*model,call("ir_fig3_accepts",ts)],quantify(
                [["i","Nat"],["p","Task"],["jid","Nat"],["j","Job"]],implies(
                    [binary("eq",call("lookup",ts,i),call("some_task",p)),
                     binary("eq",call("job_lookup",a,jid),call("some_job",j)),
                     binary("eq",call("job_task",j),i)],completion)))),
        "root":proposition(),
    }
    # @var result Existing claims also supply the exact outer context for the reviewed bridge decomposition.
    result["service_lower"] = service_bound("lower",result["response_bridge"])
    result["service_upper"] = service_bound("upper",result["response_bridge"])
    result.update(scheduling_claims())
    return result


def service_bound(direction, original):
    """Refine the terminal deadline equality into one explicitly quantified service bound.

    @param direction lower for demand <= service, or upper for service <= demand.
    @param original Exact response-bridge statement whose outer context must be preserved.
    @return New typed proposition with unchanged model premises, time domain and quantification.
    """
    # @var ts, a, s, jid, j, p Existing outer binders and newly bound job parameters.
    ts,a,s,jid,j,p = map(var,("ts","a","s","jid","j","p"))
    # @var supplied, demand Service before the absolute deadline and the job execution requirement.
    supplied = call("service",s,jid,call("release",j),binary("add",call("release",j),call("deadline",p)))
    demand = call("demand",j)
    # @var inequality, body Selected service bound guarded by job/task membership.
    inequality = binary("le",demand,supplied) if direction == "lower" else binary("le",supplied,demand)
    body = quantify([["jid","Nat"],["j","Job"],["p","Task"]],implies(
        [binary("eq",call("job_lookup",a,jid),call("some_job",j)),
         binary("eq",call("lookup",ts,call("job_task",j)),call("some_task",p))],inequality))
    # @var result, terminal Clone the original quantifiers and every premise before replacing only its conclusion.
    result = deepcopy(original)
    terminal = result
    while terminal["op"] == "forall":
        terminal = terminal["body"]
    while terminal["right"]["op"] == "implies":
        terminal = terminal["right"]
    if terminal["right"] != call("deadlines_met",ts,a,s):
        raise Rejected("unsupported_decomposition","目标结论不符合当前调度桥接拆分规则。")
    terminal["right"] = body
    render(result)
    return result



def capacity_for_job(s, jid, j, deadline):
    """Describe a concrete interval with enough capacity for this job.

    @param s Schedule expression.
    @param jid Job identity expression.
    @param j Job record expression.
    @param deadline Relative deadline expression.
    @return Existential interval length bounded by the deadline; no theorem is assumed.
    """
    # @var duration, endpoint Exclusive endpoint measured from the observed release.
    duration = var("duration")
    endpoint = binary("add",call("release",j),duration)
    return {"op":"exists","name":"duration","sort":"Nat","body":binary("and",
        binary("le",duration,deadline),
        binary("le",binary("add",call("interference",s,jid,call("release",j),endpoint),
                          call("demand",j)),duration))}


def scheduling_claims():
    """Declare general scheduling facts and the remaining analytical capacity obligation.

    @return Exact typed statements for the independently checked W06 rules.
    """
    # @var a, s, jid, j, t, u, r Job population, schedule, job, endpoints and interval start.
    a,s,jid,j,t,u,r = map(var,("a","s","jid","j","t","u","r"))
    # @var duration, deadline Arbitrary nonnegative interval and deadline lengths.
    duration,deadline = map(var,("duration","deadline"))
    # @var lookup, valid Existing job identity and the unchanged scheduler definition.
    lookup = binary("eq",call("job_lookup",a,jid),call("some_job",j))
    valid = call("valid_dm_schedule",a,s)
    # @var binders Common general-lemma parameters, independent of task acceptance.
    binders = [["a","Arrivals"],["s","Schedule"],["jid","Nat"],["j","Job"]]
    # @var release, end, supplied, blocked Half-open interval and its two slot counters.
    release = call("release",j)
    end = binary("add",release,duration)
    supplied,blocked = call("service",s,jid,release,end),call("interference",s,jid,release,end)
    # @var selected, k Executed job identity and record; equal task priority is permitted.
    selected,k = var("selected"),var("k")
    # @var dispatched Explicit existential dispatch conclusion without an added FIFO assumption.
    dispatched = {"op":"exists","name":"selected","sort":"Nat","body":
        {"op":"exists","name":"k","sort":"Job","body":binary("and",
            call("dispatches",s,t,selected),binary("and",
            binary("eq",call("job_lookup",a,selected),call("some_job",k)),binary("and",
            call("ready",s,selected,k,t),binary("le",call("job_task",k),call("job_task",j)))))}}
    # @var ts, p Task set and membership record for the still-open analysis-to-capacity step.
    ts,p = var("ts"),var("p")
    # @var model Original model conditions and workload witnesses, with no strengthened arrival restriction.
    model = [call("taskset_wf",ts),call("legal_arrivals",ts,a),call("bounded_demands",ts,a),valid,task_witnesses(ts)]
    return {
        "service_monotone":quantify([["s","Schedule"],["jid","Nat"],["r","Nat"],["u","Nat"],["t","Nat"]],
            implies([binary("le",u,t)],binary("le",call("service",s,jid,r,u),call("service",s,jid,r,t)))),
        "counters_before_release":quantify([["s","Schedule"],["jid","Nat"],["r","Nat"],["t","Nat"]],
            implies([binary("le",t,r)],binary("and",
                binary("eq",call("service",s,jid,r,t),{"op":"nat","value":0}),
                binary("eq",call("interference",s,jid,r,t),{"op":"nat","value":0})))),
        "service_never_exceeds_demand":quantify([*binders,["t","Nat"]],
            implies([valid,lookup],binary("le",call("service",s,jid,release,t),call("demand",j)))),
        "pending_dispatch":quantify([*binders,["t","Nat"]],
            implies([valid,lookup,call("ready",s,jid,j,t)],dispatched)),
        "pending_window_balance":quantify([*binders,["duration","Nat"]],
            implies([valid,lookup,binary("lt",supplied,call("demand",j))],
                    binary("eq",binary("add",supplied,blocked),duration))),
        "capacity_implies_service_lower":quantify([*binders,["deadline","Nat"]],
            implies([valid,lookup,capacity_for_job(s,jid,j,deadline)],binary("le",call("demand",j),
                call("service",s,jid,release,binary("add",release,deadline))))),
        "capacity_witnesses":quantify([["ts","TaskSet"],["a","Arrivals"],["s","Schedule"]],
            implies(model,quantify([["jid","Nat"],["j","Job"],["p","Task"]],
                implies([lookup,binary("eq",call("lookup",ts,call("job_task",j)),call("some_task",p))],
                        capacity_for_job(s,jid,j,call("deadline",p)))))),
    }
